function assignRelated(slug: string, index: number, clusterSeeds: BlogSeed[]): string[] {
  const clusterSlugs = clusterSeeds.map((s) => s.slug);
  const rotated = [
    ...clusterSlugs.filter((s) => s !== slug).slice(index % clusterSlugs.length),
    ...clusterSlugs.filter((s) => s !== slug).slice(0, index % clusterSlugs.length),
  ];
  return [...rotated.slice(0, 2), ...LEGACY_SLUG_POOL.slice(index % 3, index % 3 + 2)];
}

function buildClusterConfigs(seeds: BlogSeed[]): ExpandedBlogConfig[] {
  return seeds.map((seed, index) =>
    makeConfig(seed, assignRelated(seed.slug, index, seeds), [
      LEARN_SLUG_POOL[index % LEARN_SLUG_POOL.length],
      LEARN_SLUG_POOL[(index + 2) % LEARN_SLUG_POOL.length],
    ]),
  );
}


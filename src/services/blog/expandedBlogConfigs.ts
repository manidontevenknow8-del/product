function makeConfig(seed: BlogSeed, relatedSlugs: string[], relatedLearnSlugs?: string[]): ExpandedBlogConfig {
  return {
    slug: seed.slug,
    title: seed.title,
    excerpt: seed.excerpt,
    category: seed.category,
    tags: seed.tags,
    cluster: seed.cluster,
    focus: seed.focus,
    audience: seed.audience,
    keyDocuments: seed.keyDocuments,
    relatedSlugs,
    relatedLearnSlugs,
    faqs: [
      { question: seed.faq1, answer: seed.faq1a },
      { question: seed.faq2, answer: seed.faq2a },
      { question: seed.faq3, answer: seed.faq3a },
      {
        question: `How does PetClues help with ${seed.focus}?`,
        answer:
          'PetClues stores documents, sends reminders for due dates, and keeps an emergency passport ready to share with vets, sitters, or family.',
      },
      {
        question: `How often should I update ${seed.focus}?`,
        answer:
          'Update after every vet visit, medication change, or new document. A monthly 10-minute review catches gaps before they become problems.',
      },
      {
        question: 'Can I share records with a sitter or co-parent?',
        answer:
          'Yes. Shared access keeps everyone aligned on doses, allergies, and upcoming appointments without forwarding screenshots.',
      },
      {
        question: 'What is the fastest way to get started?',
        answer:
          'Upload your latest vet document, add the next due date as a reminder, and fill in emergency contacts. Expand history over time.',
      },
      {
        question: 'Do digital records replace my veterinarian?',
        answer:
          'No. Records support better conversations with your vet. Always confirm medical decisions with a licensed professional.',
      },
    ],
  };
}


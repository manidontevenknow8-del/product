#!/usr/bin/env node
/**
 * Generates src/services/blog/dominance/topics.generated.ts from engine catalogs.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { ENGINE_1_CATALOG } from './dominance/engine1Catalog.mjs';
import { ENGINE_2_CATALOG } from './dominance/engine2Catalog.mjs';
import { ENGINE_3_CATALOG } from './dominance/engine3Catalog.mjs';
import { ENGINE_4_CATALOG } from './dominance/engine4Catalog.mjs';
import { ENGINE_5_CATALOG } from './dominance/engine5Catalog.mjs';
import { buildTopicFromCatalog } from './dominance/buildTopic.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, '../src/services/blog/dominance/topics.generated.ts');

const catalogs = [
  [1, ENGINE_1_CATALOG],
  [2, ENGINE_2_CATALOG],
  [3, ENGINE_3_CATALOG],
  [4, ENGINE_4_CATALOG],
  [5, ENGINE_5_CATALOG],
];

const topics = [];
for (const [engine, catalog] of catalogs) {
  if (catalog.length !== 30) {
    throw new Error(`Engine ${engine} expected 30 topics, got ${catalog.length}`);
  }
  for (const entry of catalog) {
    topics.push(buildTopicFromCatalog(entry, engine));
  }
}

topics.sort((a, b) => a.num - b.num);

if (topics.length !== 150) {
  throw new Error(`Expected 150 dominance topics, got ${topics.length}`);
}

const file = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-dominance-topics.mjs - do not edit manually
import type { DominanceTopic } from './types';

export const DOMINANCE_TOPICS: DominanceTopic[] = ${JSON.stringify(topics, null, 2)} as DominanceTopic[];
`;

writeFileSync(outPath, file, 'utf8');
console.log(`Wrote ${topics.length} dominance topics to ${outPath}`);

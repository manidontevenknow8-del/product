/**
 * Validates blog image mappings and prepares hero assets.
 * - Copies custom generated photos into public/images/blog/
 * - Resizes to 1200x630 for consistent blog heroes
 * Run: npm run generate:blog-images
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const outDir = path.join(root, 'public/images/blog');
const mappingsPath = path.join(root, 'src/data/blogImageMappings.ts');

const CUSTOM_SOURCE_DIR = path.join(root, '.cursor-assets/blog');
const WORKSPACE_ASSETS = path.join(root, '..', '.cursor/projects/Users-shashank-petclues/assets');

function extractMappings() {
  const content = fs.readFileSync(mappingsPath, 'utf8');
  const map = new Map();
  for (const match of content.matchAll(/'([^']+)':\s*'(blog-[^']+\.png)'/g)) {
    map.set(match[1], match[2]);
  }
  return map;
}

function resolveCustomSource(filename) {
  const candidates = [
    path.join(CUSTOM_SOURCE_DIR, filename),
    path.join(WORKSPACE_ASSETS, filename),
    path.join(root, 'assets', filename),
  ];
  return candidates.find((candidate) => fs.existsSync(candidate)) ?? null;
}

async function prepareHero(filename, sourcePath) {
  const outPath = path.join(outDir, filename);
  await sharp(sourcePath)
    .resize(1200, 630, { fit: 'cover', position: 'centre' })
    .png({ quality: 92 })
    .toFile(outPath);
}

async function validateReuseAsset(filename) {
  const assetPath = path.join(outDir, filename);
  if (!fs.existsSync(assetPath)) {
    throw new Error(`Missing reused blog image asset: ${filename}`);
  }
}

fs.mkdirSync(outDir, { recursive: true });
fs.mkdirSync(CUSTOM_SOURCE_DIR, { recursive: true });

const mappings = extractMappings();
const customFiles = new Set();
const reuseFiles = new Set();

for (const file of mappings.values()) {
  if (
    file.startsWith('blog-labrador') ||
    file.startsWith('blog-french-bulldog') ||
    file.startsWith('blog-german-shepherd') ||
    file.startsWith('blog-poodle') ||
    file.startsWith('blog-maine-coon') ||
    file.startsWith('blog-siamese') ||
    file.startsWith('blog-dachshund') ||
    file.startsWith('blog-senior-cat') ||
    file.startsWith('blog-flying-with-cats') ||
    file.startsWith('blog-guinea-pig') ||
    file.startsWith('blog-rabbit') ||
    file.startsWith('blog-snake') ||
    file.startsWith('blog-ferret')
  ) {
    customFiles.add(file);
  } else {
    reuseFiles.add(file);
  }
}

for (const file of reuseFiles) {
  await validateReuseAsset(file);
}

let prepared = 0;
for (const file of customFiles) {
  const source = resolveCustomSource(file);
  if (!source) {
    throw new Error(`Missing custom blog image source for ${file}`);
  }
  await prepareHero(file, source);
  prepared += 1;
  console.log(`Prepared ${file}`);
}

// Remove obsolete gradient placeholders (small autogenerated heroes)
for (const entry of fs.readdirSync(outDir)) {
  if (!entry.startsWith('blog-') || !entry.endsWith('.png')) continue;
  const slugStyle = entry.match(/^blog-[a-z0-9-]{30,}\.png$/);
  if (!slugStyle) continue;
  const full = path.join(outDir, entry);
  const { size } = fs.statSync(full);
  if (size < 500_000) {
    fs.unlinkSync(full);
    console.log(`Removed obsolete placeholder ${entry}`);
  }
}

console.log(`Validated ${mappings.size} blog image mappings (${reuseFiles.size} reused, ${prepared} custom prepared)`);

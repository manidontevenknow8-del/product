#!/usr/bin/env node
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DOMINANCE_IMAGE_BY_SLUG } from './dominance/imageMap.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, '../src/data/dominanceBlogImageMappings.ts');

const slugs = Object.keys(DOMINANCE_IMAGE_BY_SLUG);
if (slugs.length !== 150) {
  throw new Error(`Expected 150 dominance image mappings, got ${slugs.length}`);
}

const heroOnly = Object.fromEntries(
  slugs.map((slug) => [slug, DOMINANCE_IMAGE_BY_SLUG[slug].hero]),
);

const file = `/* eslint-disable */
// AUTO-GENERATED by scripts/generate-dominance-image-mappings.mjs
export const DOMINANCE_BLOG_IMAGE_FILE: Record<string, string> = ${JSON.stringify(heroOnly, null, 2)};

export const DOMINANCE_BLOG_IMAGE_PAIRS: Record<string, { hero: string; inline: string }> = ${JSON.stringify(DOMINANCE_IMAGE_BY_SLUG, null, 2)};
`;

writeFileSync(outPath, file, 'utf8');
console.log(`Wrote ${slugs.length} dominance image mappings to ${outPath}`);
